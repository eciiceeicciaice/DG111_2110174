#include <stdio.h>

int main()
{
    int rows = 3;
    int cols = 5;
    int count = 1;

    // ลูปนอก (ควบคุมจำนวนแถว)
    for (int i = 0; i < rows; i++)
    {
        // พิมพ์เส้นขอบบนของแถว
        printf("+---+---+---+---+---+\n");
        // พิมพ์ตัวเปิดหน้าแถว
        printf("|");

        // ลูปใน (ควบคุมจำนวนหลักในแต่ละแถว)
        for (int j = 0; j < cols; j++)
        {
            // พิมพ์ตัวเลขจัดความกว้าง 2 หลักและเส้นแบ่งช่อง
            printf("%2d |", count);
            count++;
        }
        // เมื่อจบลูปใน ให้พิมพ์ขึ้นบรรทัดใหม่
        printf("\n");
    }

    // เมื่อจบลูปนอกทั้งหมด ให้พิมพ์เส้นขอบปิดท้ายอีก 1 ครั้ง
    printf("+---+---+---+---+---+\n");

    return 0;
}
